// Три функции, которые выбирают результат по условию.

/**
 * Знак числа: "положительное", "отрицательное" или "ноль".
 */
export function sign(n) {
  if (n > 0) {
    return "положительное";
  } else if (n < 0) {
    return "отрицательное";
  } else {
    return "ноль";
  }
}

/**
 * Оценка по баллам:
 *   90 и больше  - "отлично"
 *   от 70 до 89  - "хорошо"
 *   от 50 до 69  - "удовлетворительно"
 *   меньше 50    - "неудовлетворительно"
 */
export function grade(score) {
  if (score >= 90) {
    return "отлично";
  } else if (score >= 70) {
    return "хорошо";
  } else if (score >= 50) {
    return "удовлетворительно";
  } else {
    return "неудовлетворительно";
  }
}

/**
 * Цена билета в рублях по возрасту:
 *   младше 7 лет         - 0
 *   от 7 до 17 лет          - 150
 *   от 65 лет и старше    - 200
 *   остальные             - 400
 */
export function entryPrice(age) {
  if (age < 7) {
    return 0;
  } else if (age < 18) {
    return 150;
  } else if (age >= 65) {
    return 200;
  } else {
    return 400;
  }
}
