# Столбцы id, dept, rn: номер сотрудника внутри отдела по убыванию зарплаты
# (ROW_NUMBER, при равенстве - по возрастанию id; неизвестная зарплата - последняя).
# Только сотрудники с известным отделом. Порядок: dept, rn.
