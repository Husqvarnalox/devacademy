# Каждая константа - ОДИН запрос SELECT (можно использовать WITH и подзапросы).

# Столбцы dept, n, total: по каждому известному отделу (dept не NULL) число сотрудников n
# (COUNT(*)) и сумма зарплат total (SUM(salary); NULL игнорируются). Порядок по dept.
