#!/usr/bin/env python3
"""Generate THIRD-PARTY-NOTICES.md for the shipped desktop app.

Source of truth: `dotnet list package --include-transitive` for src/DevAcademy.Desktop (the closure that ends up in the
published app, for all target RIDs) + each package's .nuspec in the NuGet cache (license expression, authors, project URL).
Packages whose nuspec carries only a legacy licenseUrl are flagged for manual review instead of guessed.

Usage: tools/generate-third-party-notices.py [--check]   (--check exits 1 if the committed file is stale)
"""
import json, os, subprocess, sys, xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROJECT = ROOT / "src/DevAcademy.Desktop/DevAcademy.Desktop.csproj"
OUT = ROOT / "THIRD-PARTY-NOTICES.md"
# Packages whose nuspec has no SPDX expression; license text was read in the package and reviewed by hand.
REVIEWED = {
    "Avalonia.Angle.Windows.Natives": "BSD-3-Clause (ANGLE Project Authors; text in the package's LICENSE file)",
}


def packages():
    raw = subprocess.run(
        ["dotnet", "list", str(PROJECT), "package", "--include-transitive", "--format", "json"],
        check=True, capture_output=True, text=True).stdout
    found = {}
    for proj in json.loads(raw).get("projects", []):
        for fw in proj.get("frameworks", []):
            for kind, direct in (("topLevelPackages", True), ("transitivePackages", False)):
                for p in fw.get(kind, []):
                    cur = found.setdefault(p["id"], {"version": p["resolvedVersion"], "direct": direct})
                    cur["direct"] = cur["direct"] or direct
    return found


def nuget_root():
    out = subprocess.run(["dotnet", "nuget", "locals", "global-packages", "-l"], check=True, capture_output=True, text=True).stdout
    return Path(out.split(":", 1)[1].strip())


def nuspec_info(root, pid, ver):
    d = root / pid.lower() / ver.lower()
    spec = d / f"{pid.lower()}.nuspec"
    if not spec.exists():
        return None
    ns = {"n": ET.parse(spec).getroot().tag.split("}")[0].strip("{")}
    meta = ET.parse(spec).getroot().find("n:metadata", ns)
    def text(tag):
        e = meta.find(f"n:{tag}", ns)
        return (e.text or "").strip() if e is not None else ""
    lic = meta.find("n:license", ns)
    license_ = ""
    if lic is not None:
        license_ = (lic.text or "").strip() if lic.get("type") == "expression" else f"see file {(lic.text or '').strip()} in package"
    return {"license": license_, "license_url": text("licenseUrl"), "authors": text("authors"), "url": text("projectUrl")}


def main():
    subprocess.run(["dotnet", "restore", str(PROJECT), "-v", "q"], check=True, capture_output=True)
    pkgs, root = packages(), nuget_root()
    rows, review = [], []
    for pid in sorted(pkgs, key=str.lower):
        ver = pkgs[pid]["version"]
        info = nuspec_info(root, pid, ver)
        if info is None:
            review.append(f"{pid} {ver}: nuspec not found in the NuGet cache")
            rows.append((pid, ver, "UNKNOWN", "", ""))
            continue
        lic = REVIEWED.get(pid) or info["license"] or (f"legacy licenseUrl: {info['license_url']}" if info["license_url"] else "UNKNOWN")
        if lic.startswith(("legacy", "UNKNOWN", "see file")):
            review.append(f"{pid} {ver}: {lic}")
        rows.append((pid, ver, lic, info["authors"].replace("|", "/"), info["url"]))
    lines = [
        "# Third-party notices",
        "",
        "DevAcademy itself is MIT-licensed (see `LICENSE`). The desktop application bundles the NuGet packages below",
        "(direct and transitive, all target platforms). This file is generated by `tools/generate-third-party-notices.py` from",
        "`dotnet list package --include-transitive` and each package's `.nuspec`; do not edit by hand, run `make notices`.",
        "Full license texts are in the respective packages / upstream repositories.",
        "",
        "Not NuGet packages: the .NET runtime (MIT, (c) .NET Foundation and contributors) is bundled in self-contained builds;",
        "embedded fonts: IBM Plex Sans and IBM Plex Mono (SIL OFL 1.1, (c) IBM Corp.; texts in `src/DevAcademy.Desktop/Assets/Fonts`);",
        "interface icons: Lucide (ISC License, (c) Lucide Contributors, https://lucide.dev), redrawn in `Styles/Icons.axaml`;",
        "TextMate grammars come with `TextMateSharp.Grammars` (grammars from VS Code / TextMate bundles, MIT or the grammar's own license, see that package).",
        "",
        "| Package | Version | License | Authors | Project |",
        "|---|---|---|---|---|",
    ]
    for pid, ver, lic, authors, url in rows:
        lines.append(f"| {pid} | {ver} | {lic} | {authors or '—'} | {url or '—'} |")
    lines += ["", "## Needs manual review", ""]
    lines += [f"* {r}" for r in review] or ["None. (Packages without an SPDX expression were reviewed by hand; see `REVIEWED` in the generator.)"]
    text = "\n".join(lines) + "\n"
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(rows)} packages, {len(review)} need review)")


if __name__ == "__main__":
    main()
